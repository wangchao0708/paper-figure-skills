class ProbeError(RuntimeError):
    """A probe could not produce a complete, supported result."""


class ProbeBatchError(ProbeError):
    """One or more venues failed while probing all venues."""

    def __init__(self, results: dict[str, dict[str, Any]], errors: dict[str, Exception]):
        self.results = results
        self.errors = errors
        details = "; ".join(f"{venue}: {error}" for venue, error in errors.items())
        super().__init__(details)


PROBE_TEX = r"""
\makeatletter
\typeout{FIGSPEC twocolumn=\if@twocolumn 1\else 0\fi}
\typeout{FIGSPEC textwidth=\the\textwidth}
\typeout{FIGSPEC columnwidth=\the\columnwidth}
\typeout{FIGSPEC body=\f@size}
{\small\typeout{FIGSPEC small=\f@size}}
{\footnotesize\typeout{FIGSPEC footnotesize=\f@size}}
{\scriptsize\typeout{FIGSPEC scriptsize=\f@size}}
\makeatother
"""

PROBE_BODY = r"""
\par
\noindent FIGSPECBODY The quick brown fox jumps over the lazy dog.
Figure specification probe text 0123456789. This paragraph exists only to
activate the document's body font and line-breaking setup.
\par
"""

BEGIN_DOC_RE = re.compile(r"\\begin\s*\{document\}")

CORE_PACKAGE_PREFIXES = (
    "cvpr",
    "iccv",
    "neurips",
    "iclr",
    "icml",
    "acl",
    "aaai",
    "usenix",
    "sn-jnl",
)

MATH_FONT_MARKERS = (
    "cmmi",
    "cmsy",
    "cmex",
    "msam",
    "msbm",
    "stix",
    "math",
    "symbol",
    "eufm",
    "rsfs",
    "wasy",
)

NON_BODY_MARKERS = (
    "bold",
    "medi",
    "demi",
    "heavy",
    "black",
    "italic",
    "oblique",
    "slanted",
    "typewriter",
    "mono",
    "courier",
    "helvet",
    "sans",
    "ding",
    "logo",
)

YAML_HEADER = (
    "# Generated by `figspec probe`. Do not edit values by hand.\n"
    "# Template provenance: skills/paper-figure-spec/references/venue_sources.md\n"
)

PAPER_YAML_HEADER = "# Generated by `figspec probe --tex`. Do not edit values by hand.\n"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def _inject_probe(
    text: str,
    *,
    replace_body_placeholder: bool,
    after_maketitle: bool = False,
) -> str:
    insertion = "\n" + PROBE_TEX + PROBE_BODY
    if replace_body_placeholder:
        if "%%BODY%%" in text:
            return text.replace("%%BODY%%", insertion, 1)
        raise ProbeError("min.tex does not contain the %%BODY%% placeholder")

    begin_match = None
    for match in BEGIN_DOC_RE.finditer(text):
        line_start = text.rfind("\n", 0, match.start()) + 1
        if "%" not in text[line_start : match.start()]:
            begin_match = match
            break
    if begin_match is None:
        raise ProbeError("no uncommented \\begin{document} found")

    if after_maketitle:
        # Some classes (notably acmart) switch to the final column layout only
        # inside \maketitle; measuring before that point yields the title's
        # full-width geometry.
        for match in re.finditer(r"\\maketitle\b", text[begin_match.end() :]):
            start = begin_match.end() + match.start()
            end = begin_match.end() + match.end()
            line_start = text.rfind("\n", 0, start) + 1
            if "%" not in text[line_start:start]:
                return text[:end] + insertion + text[end:]

    return text[: begin_match.end()] + insertion + text[begin_match.end() :]


def _documentclass_and_packages(text: str) -> str:
    match = re.search(
        r"\\documentclass\s*(?:\[(?P<opts>[^\]]*)\])?\s*\{(?P<cls>[^}]+)\}",
        text,
        re.S,
    )
    if not match:
        raise ProbeError("no \\documentclass declaration found")
    cls = re.sub(r"\s+", "", match.group("cls"))
    opts = match.group("opts")
    if opts:
        normalized_opts = ",".join(part.strip() for part in opts.split(",") if part.strip())
        declaration = f"{cls}[{normalized_opts}]"
    else:
        declaration = cls

    core_packages: list[str] = []
    for package_match in re.finditer(
        r"\\usepackage\s*(?:\[(?P<opts>[^\]]*)\])?\s*\{(?P<names>[^}]*)\}",
        text,
        re.S,
    ):
        package_opts = package_match.group("opts")
        for name in package_match.group("names").split(","):
            name = name.strip()
            if not name:
                continue
            if any(name.startswith(prefix) for prefix in CORE_PACKAGE_PREFIXES):
                if package_opts:
                    normalized_opts = ",".join(
                        part.strip() for part in package_opts.split(",") if part.strip()
                    )
                    rendered = f"{name}[{normalized_opts}]"
                else:
                    rendered = name
                if rendered not in core_packages:
                    core_packages.append(rendered)

    if core_packages:
        return f"{declaration} + {', '.join(core_packages)}"
    return declaration


def _copy_project(source: Path, destination: Path) -> None:
    ignore = shutil.ignore_patterns(
        ".git",
        ".hg",
        ".svn",
        "__pycache__",
        ".DS_Store",
        "*.egg-info",
        ".venv",
        "venv",
        "*.aux",
        "*.log",
        "*.out",
        "*.fls",
        "*.fdb_latexmk",
        "*.synctex.gz",
    )
    shutil.copytree(source, destination, ignore=ignore, symlinks=True)


def _compile(project: Path, tex_name: str, outdir: Path) -> Path:
    latexmk = shutil.which("latexmk")
    if not latexmk:
        raise ProbeError("latexmk not found in PATH")
    outdir.mkdir(parents=True, exist_ok=True)
    command = [
        latexmk,
        "-pdf",
        "-interaction=nonstopmode",
        "-halt-on-error",
        "-file-line-error",
        f"-outdir={outdir}",
        tex_name,
    ]
    env = os.environ.copy()
    # Keep long log lines from being wrapped at 79 characters.
    env.setdefault("max_print_line", "10000")
    try:
        proc = subprocess.run(
            command,
            cwd=project,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=300,
        )
    except subprocess.TimeoutExpired as exc:
        raise ProbeError(f"latexmk timed out for {tex_name}") from exc

    stem = Path(tex_name).stem
    log_path = outdir / f"{stem}.log"
    pdf_path = outdir / f"{stem}.pdf"
    if proc.returncode != 0 or not pdf_path.exists():
        log_tail = ""
        if log_path.exists():
            log_tail = "\n".join(log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-25:])
        raise ProbeError(
            f"latexmk failed for {tex_name}\n"
            f"{log_tail or proc.stdout[-2500:]}"
        )
    return pdf_path


def _log_value(log: str, key: str) -> str:
    values = re.findall(rf"FIGSPEC\s+{re.escape(key)}=([^\s]+)", log)
    if not values:
        raise ProbeError(f"missing FIGSPEC {key}= value in TeX log")
    if len(set(values)) > 1:
        raise ProbeError(f"inconsistent FIGSPEC {key}= values: {values}")
    return values[-1]


def _parse_pt(value: str, key: str) -> float:
    match = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)pt", value)
    if not match:
        raise ProbeError(f"cannot parse {key} as TeX pt: {value!r}")
    return round(float(match.group(1)), 2)


def _parse_size(value: str, key: str) -> float:
    try:
        return round(float(value), 2)
    except ValueError as exc:
        raise ProbeError(f"cannot parse {key} as a font size: {value!r}") from exc


def _read_fonts(pdf: Path) -> list[str]:
    pdffonts = shutil.which("pdffonts")
    if not pdffonts:
        raise ProbeError("pdffonts not found in PATH")
    proc = subprocess.run(
        [pdffonts, str(pdf)],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=60,
    )
    if proc.returncode != 0:
        raise ProbeError(f"pdffonts failed for {pdf}:\n{proc.stdout[-2000:]}")
    lines = proc.stdout.splitlines()
    try:
        separator = next(i for i, line in enumerate(lines) if line.startswith("---"))
    except StopIteration as exc:
        raise ProbeError(f"unexpected pdffonts output for {pdf}:\n{proc.stdout[-2000:]}") from exc

    fonts: list[str] = []
    for line in lines[separator + 1 :]:
        parts = line.split()
        if not parts:
            continue
        name = re.sub(r"^[A-Z]{6}\+", "", parts[0])
        if name and name not in fonts:
            fonts.append(name)
    if not fonts:
        raise ProbeError(f"pdffonts found no fonts in {pdf}")
    return fonts


def _font_from_marker(pdf: Path, fonts: list[str]) -> str | None:
    """Find the pdffonts entry used for the explicit body marker.

    pdffonts supplies the authoritative font names and embedding information;
    PyMuPDF is only used to disambiguate which listed font the probe body uses.
    """
    with fitz.open(pdf) as doc:
        for page in doc:
            for block in page.get_text("dict").get("blocks", []):
                for line in block.get("lines", []):
                    for span in line.get("spans", []):
                        if "FIGSPECBODY" not in span.get("text", ""):
                            continue
                        span_font = re.sub(r"^[A-Z]{6}\+", "", span.get("font", ""))
                        if not span_font:
                            continue
                        for font in fonts:
                            if font.casefold() == span_font.casefold():
                                return font
                        for font in fonts:
                            if font.casefold() in span_font.casefold() or span_font.casefold() in font.casefold():
                                return font
    return None


def _looks_like_body_font(name: str) -> bool:
    low = name.casefold()
    if any(marker in low for marker in MATH_FONT_MARKERS):
        return False
    if any(marker in low for marker in NON_BODY_MARKERS):
        return False
    return True


def _choose_body_font(pdf: Path, fonts: list[str]) -> str:
    marker_font = _font_from_marker(pdf, fonts)
    if marker_font:
        return marker_font
    for font in fonts:
        if _looks_like_body_font(font):
            return font
    return fonts[0]


def classify_family(font: str) -> str:
    low = re.sub(r"[^a-z0-9]+", "", font.casefold())
    if "libertine" in low:
        return "libertine"
    if any(marker in low for marker in ("times", "nimbusrom", "nimbusroman", "termes", "tinos")):
        return "times"
    if low.startswith(("ptm", "ptmr", "ptmb")):
        return "times"
    if low.startswith(("cmr", "lmr", "lmroman", "latinmodern", "computermodern")):
        return "cm"
    if "cmuserif" in low:
        return "cm"
    return "other"


def _record(
    *,
    venue: str,
    source: str,
    class_opts: str,
    pdf: Path,
) -> dict[str, Any]:
    log_path = pdf.with_suffix(".log")
    log = log_path.read_text(encoding="utf-8", errors="replace")
    twocolumn = _log_value(log, "twocolumn") == "1"
    textwidth_pt = _parse_pt(_log_value(log, "textwidth"), "textwidth")
    columnwidth_pt = _parse_pt(_log_value(log, "columnwidth"), "columnwidth")
    body_pt = _parse_size(_log_value(log, "body"), "body")
    small_pt = _parse_size(_log_value(log, "small"), "small")
    footnotesize_pt = _parse_size(_log_value(log, "footnotesize"), "footnotesize")
    scriptsize_pt = _parse_size(_log_value(log, "scriptsize"), "scriptsize")

    fonts = _read_fonts(pdf)
    body_font = _choose_body_font(pdf, fonts)
    family = classify_family(body_font)
    if family == "other":
        raise ProbeError(
            f"{venue}: unsupported body font family for {body_font!r}; "
            f"pdffonts reported {', '.join(fonts)}"
        )

    return {
        "source": source,
        "class_opts": class_opts,
        "twocolumn": twocolumn,
        "textwidth_pt": textwidth_pt,
        "columnwidth_pt": columnwidth_pt,
        "body_pt": body_pt,
        "small_pt": small_pt,
        "footnotesize_pt": footnotesize_pt,
        "scriptsize_pt": scriptsize_pt,
        "body_font": body_font,
        "family": family,
        "probed_at": _now(),
        "aliases": list(ALIASES[venue]),
    }


def probe_template(venue: str) -> dict[str, Any]:
    try:
        canonical = resolve_venue(venue)
    except ValueError as exc:
        raise ProbeError(str(exc)) from exc
    template_dir = repo_root() / "templates" / canonical
    source_tex = template_dir / "min.tex"
    if not source_tex.exists():
        raise ProbeError(f"template not found: {source_tex}")
    original = source_tex.read_text(encoding="utf-8")
    class_opts = _documentclass_and_packages(original)

    with tempfile.TemporaryDirectory(prefix="figspec-probe-") as tmp:
        root = Path(tmp)
        project = root / "project"
        outdir = root / "out"
        _copy_project(template_dir, project)
        patched = _inject_probe(original, replace_body_placeholder=True)
        (project / "min.tex").write_text(patched, encoding="utf-8")
        pdf = _compile(project, "min.tex", outdir)
        return _record(
            venue=canonical,
            source=f"templates/{canonical}/min.tex",
            class_opts=class_opts,
            pdf=pdf,
        )


def probe_paper(tex: str | Path, venue: str) -> dict[str, Any]:
    try:
        canonical = resolve_venue(venue)
    except ValueError as exc:
        raise ProbeError(str(exc)) from exc
    main_tex = Path(tex).expanduser().resolve()
    if not main_tex.is_file():
        raise ProbeError(f"paper main file not found: {main_tex}")
    original = main_tex.read_text(encoding="utf-8")
    class_opts = _documentclass_and_packages(original)
    paper_root = main_tex.parent

    with tempfile.TemporaryDirectory(prefix="figspec-probe-") as tmp:
        root = Path(tmp)
        project = root / "project"
        outdir = root / "out"
        _copy_project(paper_root, project)
        patched = _inject_probe(
            original,
            replace_body_placeholder=False,
            # acmart keeps the title full-width and only enters the final
            # two-column layout inside \maketitle.
            after_maketitle=class_opts.startswith("acmart"),
        )
        (project / main_tex.name).write_text(patched, encoding="utf-8")
        pdf = _compile(project, main_tex.name, outdir)
        record = _record(
            venue=canonical,
            source=main_tex.name,
            class_opts=class_opts,
            pdf=pdf,
        )
    record = {"venue": canonical, **record}
    _write_paper_spec(paper_root / ".figspec.yaml", record)
    return record


def probe_all() -> dict[str, dict[str, Any]]:
    results: dict[str, dict[str, Any]] = {}
    errors: dict[str, Exception] = {}
    for venue in VENUES:
        try:
            results[venue] = probe_template(venue)
        except Exception as exc:  # keep probing so the caller gets a full report
            errors[venue] = exc
    if errors:
        raise ProbeBatchError(results, errors)
    return results


def _write_yaml(path: Path, data: dict[str, Any], *, header: str = YAML_HEADER) -> None:
    rendered = yaml.safe_dump(
        data,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=1000,
    )
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(header + rendered, encoding="utf-8")
    tmp.replace(path)


def save_venue(venue: str, record: dict[str, Any]) -> Path:
    data = load_venue_data()
    data.setdefault("venues", {})[venue] = record
    path = venues_path()
    _write_yaml(path, data)
    return path


def save_all_venues(results: dict[str, dict[str, Any]]) -> Path:
    data = load_venue_data()
    data["venues"] = {venue: results[venue] for venue in VENUES}
    path = venues_path()
    _write_yaml(path, data)
    return path


def _write_paper_spec(path: Path, record: dict[str, Any]) -> None:
    _write_yaml(path, record, header=PAPER_YAML_HEADER)


def _fmt_size(value: float) -> str:
    return f"{value:g}"


def format_table(results: dict[str, dict[str, Any]]) -> str:
    header = (
        f"{'venue':<10} {'twocolumn':<10} {'columnwidth':>12} {'textwidth':>10} "
        f"{'body':>5} {'small/foot/script':<18} {'family':<10}"
    )
    lines = [header, "-" * len(header)]
    for venue in VENUES:
        if venue not in results:
            continue
        item = results[venue]
        trinary = "/".join(
            _fmt_size(item[key]) for key in ("small_pt", "footnotesize_pt", "scriptsize_pt")
        )
        lines.append(
            f"{venue:<10} {('yes' if item['twocolumn'] else 'no'):<10} "
            f"{item['columnwidth_pt']:>12.1f} {item['textwidth_pt']:>10.1f} "
            f"{_fmt_size(item['body_pt']):>5} {trinary:<18} {item['family']:<10}"
        )
    return "\n".join(lines)
